import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { copyFile, mkdtemp, rm, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { chromium } from 'playwright';
import { load, server } from '../src/server.mjs';
import { readWorkbookManualOverrides } from '../src/workbook.mjs';

test('real-data React views, account filters, drilldowns and durable retags work', async context => {
  const root = process.cwd();
  if (!existsSync(join(root, 'master_transactions.xlsx'))) return context.skip('Local ledger required');
  const temporary = await mkdtemp(join(tmpdir(), 'money-react-test-'));
  await copyFile(join(root, 'master_transactions.xlsx'), join(temporary, 'master_transactions.xlsx'));
  for (const folder of ['POSB:DBS Bank Statement', 'PayLah', 'Revolut', 'config']) await symlink(join(root, folder), join(temporary, folder), 'dir');
  process.chdir(temporary);
  context.after(async () => { process.chdir(root); await rm(temporary, { recursive: true, force: true }); });
  await load();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  context.after(() => new Promise(resolve => server.close(resolve)));
  const url = `http://127.0.0.1:${server.address().port}`;
  const api = async () => (await fetch(`${url}/api/data`)).json();
  const initial = await api();
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--no-sandbox'] });
  context.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.locator('.metric-card').first().waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.flow-chart .recharts-area-curve[d]').length === 3);
  assert.equal(await page.locator('.metric-card').count(), 3);
  assert.ok(await page.locator('.month-tick').count() >= 9);
  await page.getByRole('button', { name: 'Year', exact: true }).click();
  const format = value => new Intl.NumberFormat('en-SG', { style: 'currency', currency: 'SGD', maximumFractionDigits: 0, minimumFractionDigits: 0 }).format(value);
  assert.ok((await page.locator('.metric-card').first().innerText()).includes(format(initial.metrics.months.reduce((sum, row) => sum + row.netIncomeSgd, 0))));
  await page.locator('.analysis-switch').first().getByRole('button', { name: 'Balance', exact: true }).click();
  assert.ok(await page.locator('.recharts-area').count());
  await page.getByRole('button', { name: 'Accounts and source coverage', exact: true }).click();
  assert.equal(await page.locator('.account-summary').count(), initial.accounts.length);
  assert.equal(await page.locator('.source-gap').count(), initial.sourceGaps.length);
  await page.keyboard.press('Escape');
  await page.locator('.category-bar-row').first().click();
  assert.equal(await page.getByRole('button', { name: 'Categories', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.locator('.category-index-row').filter({ hasText: 'Food & Dining' }).click();
  assert.ok(await page.locator('.category-subcategory').count());
  await page.locator('.category-subcategory').first().click();
  assert.ok((await page.locator('.category-transactions').innerText()).includes('Clear filter'));
  await page.locator('.category-transaction-link').first().click();
  assert.equal(await page.getByRole('button', { name: 'Transactions', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('.transaction-row-focused').count(), 1);

  // Retag only the temporary workbook; keep the user's ledger untouched.
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.getByRole('button', { name: 'Transactions', exact: true }).click();
  await page.locator('.filterbar select').nth(2).selectOption('All time');
  const sample = initial.transactions.find(row => row.role === 'expense' && row.amountSgd < 0 && row.accountId !== initial.relationship.accountId && !row.manualCategory);
  assert.ok(sample);
  await page.getByPlaceholder('Search transactions').fill(sample.descriptionRaw);
  const row = page.locator(`[id="transaction-${sample.id}"]`);
  await row.waitFor();
  const changedCategory = sample.category === 'Shopping' ? 'Food & Dining' : 'Shopping';
  const savedResponse = page.waitForResponse(response => response.url().includes('/api/transactions/') && response.request().method() === 'POST');
  await row.locator('select').first().selectOption(changedCategory);
  assert.equal((await savedResponse).status(), 200);
  assert.equal((await api()).transactions.find(item => item.id === sample.id).manualCategory, changedCategory);
  assert.equal((await readWorkbookManualOverrides()).get(sample.id).manualCategory, changedCategory);
  await row.getByRole('button', { name: /More details/ }).click();
  const resetResponse = page.waitForResponse(response => response.url().includes('/api/transactions/') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Reset to automatic', exact: true }).click();
  assert.equal((await resetResponse).status(), 200);
  assert.equal((await api()).transactions.find(item => item.id === sample.id).manualCategory, null);
  await page.keyboard.press('Escape');

  await page.getByPlaceholder('Search transactions').fill('');
  await page.getByRole('button', { name: 'All accounts', exact: true }).click();
  const accountButton = page.locator('.account-menu button').first();
  const accountName = await accountButton.innerText();
  await accountButton.click();
  assert.ok((await page.locator('tbody tr .account-chip').allTextContents()).every(name => name === accountName));
  await page.getByRole('button', { name: '1 accounts', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  assert.match((await download).suggestedFilename(), /transactions.*\.csv/);
  await page.getByRole('button', { name: initial.relationship.accountName, exact: true }).click();
  assert.ok((await page.locator('tbody tr .account-chip').allTextContents()).every(name => name === initial.relationship.accountName));
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  assert.match(await page.locator('.savings-card').innerText(), /ledger/i);
  await page.getByRole('button', { name: 'Personal finances', exact: true }).click();
  await page.getByRole('button', { name: /Savings estimator/ }).click();
  const projection = page.locator('.projection-card').last();
  const previousProjection = await projection.innerText();
  await page.getByRole('spinbutton', { name: 'Forecast monthly spending', exact: true }).fill('0');
  assert.notEqual(await projection.innerText(), previousProjection);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Calendar', exact: true }).click();
  await page.locator('.calendar-panel select').selectOption('Food & Dining');
  assert.ok(await page.locator('.calendar-day').count() >= 28);
  await page.locator('.calendar-day').first().click();
  assert.match(await page.locator('.day-panel').innerText(), /Selected day/i);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  await page.waitForFunction(() => document.querySelector('.flow-chart svg')?.getBoundingClientRect().height > 200 && document.querySelectorAll('.flow-chart .recharts-area-curve[d]').length === 3);
  await page.screenshot({ path: '/private/tmp/money-gaze-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
});
